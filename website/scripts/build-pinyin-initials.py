"""Generate the browser's offline initials table: pypinyin==0.55.0 (MIT).

Run with that package on PYTHONPATH; no Python dependency is needed at runtime.
All dictionary readings are retained for polyphonic names. This is a retrieval
index only, never a teacher identity or course equivalence rule.
"""
from collections import defaultdict
from pathlib import Path
import importlib.metadata
import json
import unicodedata

from pypinyin import __version__
from pypinyin.pinyin_dict import pinyin_dict

if __version__ != '0.55.0':
    raise RuntimeError('Expected pypinyin==0.55.0')

root = Path(__file__).resolve().parents[1]
groups = defaultdict(str)
for codepoint, readings in sorted(pinyin_dict.items()):
    initials = set()
    for reading in readings.split(','):
        plain = unicodedata.normalize('NFD', reading).lower()
        if plain and 'a' <= plain[0] <= 'z':
            initials.add(plain[0])
    if initials:
        groups[''.join(sorted(initials))] += chr(codepoint)

target = root / 'dist' / 'pinyin-initials-data.mjs'
target.write_text(
    '// Generated by scripts/build-pinyin-initials.py from pypinyin 0.55.0 (MIT).\n'
    '// License: vendor/pypinyin-LICENSE.txt. Retain all readings for initials search.\n'
    'export const initialGroups = Object.freeze(' +
    json.dumps(dict(sorted(groups.items())), ensure_ascii=False, separators=(',', ':')) +
    ');\n', encoding='utf-8')

package = importlib.metadata.distribution('pypinyin')
licenses = [f for f in package.files if f.name == 'LICENSE.txt']
if len(licenses) != 1:
    raise RuntimeError('Cannot identify the package license')
license_dir = root / 'dist' / 'vendor'
license_dir.mkdir(exist_ok=True)
(license_dir / 'pypinyin-LICENSE.txt').write_text(
    package.locate_file(licenses[0]).read_text(encoding='utf-8'), encoding='utf-8')
print(json.dumps({'characters': sum(map(len, groups.values())), 'bytes': target.stat().st_size}))
